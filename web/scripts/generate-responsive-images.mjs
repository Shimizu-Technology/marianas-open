import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const imageDir = path.join(root, 'public/images');
await mkdir(path.join(imageDir, 'responsive'), { recursive: true });
const sources = {};
for (const file of ['venue-crowd.webp', 'action-match-1.webp', 'action-match-2.webp', 'hero-podium.jpg', 'podium-1.webp', 'ceremony-1.webp', 'ceremony-2.webp']) {
  const original = path.join(imageDir, file);
  const { width } = await sharp(original).metadata();
  const variants = [];
  for (const size of [640, 960].filter(size => size < width)) {
    const name = `${path.parse(file).name}-${size}.webp`;
    await sharp(original).resize({ width: size, withoutEnlargement: true }).webp({ quality: 80 }).toFile(path.join(imageDir, 'responsive', name));
    variants.push(`/images/responsive/${name} ${size}w`);
  }
  variants.push(`/images/${file} ${width}w`);
  sources[`/images/${file}`] = variants.join(', ');
}
await writeFile(path.join(root, 'src/utils/responsiveImages.ts'), `// Generated by scripts/generate-responsive-images.mjs. API originals have no resize endpoint.\nconst localSources: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n\nexport function getLocalImageSrcSet(src: string): string | undefined {\n  return localSources[src];\n}\n`);
