import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { MemoryRouter } from 'react-router-dom'
import { api } from '../../services/api'
import AcademiesAdmin from './AcademiesAdmin'
import CompetitorsAdmin from './CompetitorsAdmin'
import { academyFixture, competitorFixture, listResponse } from '../../components/admin/identityFixtures'

vi.mock('../../components/ImageUpload', () => ({ default: () => <div>Image upload</div> }))
beforeEach(() => {
  vi.spyOn(api.admin, 'getAcademies').mockResolvedValue({ academies: [], ...listResponse, total: 0 })
  vi.spyOn(api.admin, 'getCompetitors').mockResolvedValue({ competitors: [], ...listResponse, total: 0 })
  vi.spyOn(api.admin, 'getAcademy').mockImplementation(async id => ({ academy: { ...academyFixture(id, id === 7 ? 'Source Gym' : 'Parent Gym'), athletes: [] } }))
  vi.spyOn(api.admin, 'getCompetitor').mockImplementation(async id => ({ competitor: { ...competitorFixture(id, 'Original Athlete'), results: [], academy_slug: null } }))
  vi.spyOn(api.admin, 'updateAcademy').mockResolvedValue({ academy: academyFixture(7, 'Renamed Gym') })
  vi.spyOn(api.admin, 'updateCompetitor').mockResolvedValue({ competitor: competitorFixture(7, 'Corrected Name') })
})
afterEach(() => { cleanup(); vi.restoreAllMocks() })
const renderEditor = (kind: 'academies' | 'competitors') => render(<MemoryRouter initialEntries={[`/admin/${kind}?edit=7`]}>{kind === 'academies' ? <AcademiesAdmin /> : <CompetitorsAdmin />}</MemoryRouter>)

it('hydrates an academy outside the list page, then saves rename, location, alpha-3 country, parent, and unaffiliated edits', async () => {
  renderEditor('academies')
  const name = await screen.findByRole('textbox', { name: 'Academy Name *' })
  await waitFor(() => expect((name as HTMLInputElement).value).toBe('Source Gym'))
  fireEvent.change(name, { target: { value: 'Renamed Gym' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Location' }), { target: { value: 'Tamuning, Guam' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Country Code' }), { target: { value: 'gum' } })
  fireEvent.click(screen.getByRole('checkbox', { name: 'Unaffiliated / no gym' }))
  vi.mocked(api.admin.getAcademies).mockResolvedValue({ academies: [academyFixture(90, 'Parent Gym')], ...listResponse })
  fireEvent.change(screen.getByRole('searchbox', { name: 'Parent academy (optional)' }), { target: { value: 'Parent' } })
  fireEvent.click(await screen.findByRole('button', { name: /Parent Gym \(ID 90\)/ }))
  expect(screen.getByText(/Save profile changes and finish loading/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  await waitFor(() => expect(api.admin.updateAcademy).toHaveBeenCalledWith(7, expect.objectContaining({ name: 'Renamed Gym', location: 'Tamuning, Guam', country_code: 'GUM', parent_id: 90, unaffiliated: true })))
  await screen.findByText('Academy updated')
})
it('preserves saved parent and unaffiliated values and explicitly removes a parent', async () => {
  vi.mocked(api.admin.getAcademy).mockImplementation(async id => ({ academy: { ...academyFixture(id, id === 7 ? 'Source Gym' : 'Parent Gym'), athletes: [], parent_id: id === 7 ? 90 : null, unaffiliated: true } }))
  renderEditor('academies')
  await screen.findByRole('button', { name: 'Remove parent academy' })
  expect((screen.getByRole('checkbox', { name: 'Unaffiliated / no gym' }) as HTMLInputElement).checked).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  await waitFor(() => expect(api.admin.updateAcademy).toHaveBeenCalledWith(7, expect.objectContaining({ parent_id: 90, unaffiliated: true })))
  await screen.findByText('Academy updated')
  fireEvent.click(screen.getByRole('button', { name: 'Remove parent academy' }))
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  await waitFor(() => expect(api.admin.updateAcademy).toHaveBeenLastCalledWith(7, expect.objectContaining({ parent_id: null })))
})
it('renames first and last names from an off-page competitor profile', async () => {
  renderEditor('competitors')
  const first = await screen.findByRole('textbox', { name: 'First Name *' })
  await waitFor(() => expect((first as HTMLInputElement).value).toBe('Original'))
  fireEvent.change(first, { target: { value: 'Corrected' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Last Name *' }), { target: { value: 'Name' } })
  expect(screen.getByText(/Save profile changes and finish loading/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  await waitFor(() => expect(api.admin.updateCompetitor).toHaveBeenCalledWith(7, expect.objectContaining({ first_name: 'Corrected', last_name: 'Name' })))
  await screen.findByText('Competitor updated')
})
it('preserves an unsuccessful rename draft and allows retry', async () => {
  vi.mocked(api.admin.updateCompetitor).mockRejectedValueOnce(new Error('Name is invalid'))
  renderEditor('competitors')
  const first = await screen.findByRole('textbox', { name: 'First Name *' })
  await waitFor(() => expect((first as HTMLInputElement).value).toBe('Original'))
  fireEvent.change(first, { target: { value: 'Corrected' } })
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  expect((await screen.findByRole('alert')).textContent).toContain('Name is invalid')
  expect((first as HTMLInputElement).value).toBe('Corrected')
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
  await screen.findByText('Competitor updated')
})
it.each(['academies', 'competitors'] as const)('blocks saving after a %s detail failure and recovers through retry', async kind => {
  if (kind === 'academies') vi.mocked(api.admin.getAcademy).mockRejectedValueOnce(new Error('Session expired'))
  else vi.mocked(api.admin.getCompetitor).mockRejectedValueOnce(new Error('Session expired'))
  renderEditor(kind)
  expect((await screen.findByRole('alert')).textContent).toContain('Session expired')
  expect((screen.getByRole('button', { name: 'Save' }) as HTMLButtonElement).closest('fieldset')?.disabled).toBe(true)
  expect(screen.queryByRole('region', { name: /Merge/ })).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Retry profile' }))
  await screen.findByRole('region', { name: kind === 'academies' ? 'Merge academy' : 'Merge competitor' })
  expect((screen.getByRole('button', { name: 'Save' }) as HTMLButtonElement).closest('fieldset')?.disabled).toBe(false)
})
it('opens the surviving profile after a successful merge even when it is outside the table page', async () => {
  vi.spyOn(api.admin, 'previewCompetitorMerge').mockResolvedValue({ source: { id: 7, name: 'Original Athlete' }, target: { id: 900, name: 'Target Athlete' }, results_count: 7, warnings: [], blocked: false })
  vi.spyOn(api.admin, 'mergeCompetitor').mockResolvedValue({ competitor: competitorFixture(900, 'Target Athlete') })
  renderEditor('competitors')
  await screen.findByRole('region', { name: 'Merge competitor' })
  vi.mocked(api.admin.getCompetitors).mockResolvedValue({ competitors: [competitorFixture(900)], ...listResponse })
  fireEvent.change(screen.getByRole('searchbox', { name: 'Keep this record' }), { target: { value: 'Target' } })
  fireEvent.click(await screen.findByRole('button', { name: /Target Athlete \(ID 900\)/ }))
  fireEvent.click(screen.getByRole('button', { name: 'Preview merge' }))
  fireEvent.click(await screen.findByRole('checkbox', { name: /Permanently merge/ }))
  fireEvent.click(screen.getByRole('button', { name: 'Permanently merge records' }))
  await waitFor(() => expect(api.admin.getCompetitor).toHaveBeenCalledWith(900))
  expect(await screen.findByText('Merged competitor into Target Athlete (ID 900).')).toBeTruthy()
})
